/* ================================================================
 * swos_globals_career_overlay.c
 *
 * Generated alias block for the careerFileBuffer BSS run.
 *
 * On the Amiga the 338 labels between `careerFileBuffer:` and
 * `numSelectedTeams:` (inclusive) sit in one contiguous `ds.b`
 * region, so the on-disk save file is just the bytes of that
 * region.  `_SaveCareerFile` writes raw bytes from
 * `&careerFileBuffer` for ~98 KB + numSelectedTeams * 684 + 2.
 *
 * On SDL each global landed in its own .o symbol, so writes via
 * the named global never made it into the file buffer.  Aliasing
 * each label to its computed offset inside `careerFileBufferBuf`
 * (defined in swos_globals.c) restores the Amiga overlay so save
 * and load round-trip the way the original code expects.
 *
 * The 7 already-aliased labels (careerFileBuffer + the saveFile*
 * header at the tail) live in swos_globals.c and are NOT
 * re-emitted here.
 *
 * BSS_01_xxx and pad_xxx anonymous holes are unreferenced and are
 * also skipped.
 *
 * Offsets generated by walking SWOS2.s ds.b allocations from
 * `careerFileBuffer:`. See memory file project_career_buffer_overlay.md.
 * ================================================================ */

