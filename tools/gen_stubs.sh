#!/usr/bin/env bash
# tools/gen_stubs.sh -- regenerate src/swos_amiga_data_stubs.c from the
# current set of unresolved-symbol link errors.
#
# Usage:
#   tools/gen_stubs.sh
#
# Re-run any time the link error list changes (e.g. after deleting a
# data symbol that now lives in a real C file).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ASM="/mnt/c/Projects/AI/SWOS/SWOS_C/SWOS2.s"
OUT="$ROOT/src/swos_amiga_data_stubs.c"

cd "$ROOT"

# 1. Build a fresh missing-symbol list
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

PKG_CONFIG_PATH=/usr/lib/i386-linux-gnu/pkgconfig make 2>&1 \
  | grep "undefined reference to" \
  | sed -E "s/.*undefined reference to \`([^']+)'.*/\1/" \
  | sort -u > "$TMP/missing.txt"

# 2. Classify each symbol
awk -v list="$TMP/missing.txt" '
BEGIN { while ((getline l < list) > 0) want[l]=1 }
/^[A-Za-z_][A-Za-z0-9_]*:/ {
  s=$1; sub(":","",s); if (s in want) cur=s; else cur=""; next
}
cur && /^\s*movem|^\s*move|^\s*jsr|^\s*rts|^\s*bra|^\s*bsr|^\s*bne|^\s*beq|^\s*lea|^\s*addq|^\s*subq|^\s*tst|^\s*cmp|^\s*and|^\s*or\s/ {
  kind[cur]="func"; cur=""; next
}
cur && /^\s*dc\.|^\s*ds\./ { kind[cur]="data"; cur=""; next }
END { for (s in want) print (s in kind ? kind[s] : "unk"), s }
' "$ASM" | sort > "$TMP/kind.txt"

# 3. Extract `ds.b` sizes
awk '
/^[A-Za-z_][A-Za-z0-9_]*:/ { cur=$1; sub(":","",cur); next }
cur && /ds\.b/ {
  for (i=1;i<=NF;i++) if ($i=="ds.b") {
    sz=$(i+1); sub("\\$","0x",sz); print cur, sz; break
  }
  cur=""
}
' "$ASM" > "$TMP/sizes.txt"

# Only emit *real* data symbols. Any "unk" that's actually a function
# (e.g. _SafeStart, Int4Handler) must be added to swos_amiga_func_stubs.c
# by hand. Unknown *data* symbols still need a stub though, so we
# include them by default and hand-remove the function-shaped ones.
awk '$1=="data" || $1=="unk" {print $2}' "$TMP/kind.txt" > "$TMP/data_syms.txt"

# 4. Emit the stub C file
{
  cat <<EOF
/*
 * swos_amiga_data_stubs.c -- AUTO-GENERATED by tools/gen_stubs.sh
 * Do not hand-edit; regenerate after changing real symbol definitions.
 *
 * Each symbol is sized at max(ds.b N from SWOS2.s, 4 KiB). The 4 KiB
 * floor is a safety margin -- some Amiga code intentionally writes past
 * the declared size of a buffer ("boundary spill"), trusting the next
 * symbol in the data section to absorb the overflow. We can't preserve
 * that ordering on a hosted target, so we widen each stub instead.
 */
#include <stddef.h>

EOF
  awk 'NR==FNR { sz[$1]=$2; next }
       {
         s = ($1 in sz) ? sz[$1] : "4096"
         # Minimum 4 KiB
         n = strtonum(s)
         if (n < 4096) s = "4096"
         printf "char %s[%s];\n", $1, s
       }' "$TMP/sizes.txt" "$TMP/data_syms.txt"
} > "$OUT"

echo "Wrote $OUT ($(wc -l < "$OUT") lines)"
