#!/usr/bin/env python3
"""Generate src/menu_symbols.{c,h} — the menu name->address registry.

See docs/MENUS.md §2c. Menus serialized to JSON store every callback / string /
string-table / sprite-copy / buffer as a SYMBOL NAME (never an address, per the
CLAUDE.md "pointers as semantic identity" rule). This registry is the single
place that maps those names back to real addresses; it is used by the SDL JSON
loader (menu_load_json.c) and, eventually, the Amiga relocation patcher.

Inputs:
  bin/data_json/menus/_symbols.json   (produced by scripts/export_menus.py)
  src/menu_data.c                     (harvested for the exact extern decls)

Strategy: function symbols are uniformly `void (*)(void)` for address-taking
purposes, so they're declared `extern void NAME(void);` exactly as menu_data.c
declares them (menu_symbols.c includes only menu_data.h, so there are no
conflicting prototypes — same self-contained trick menu_data.c uses). Data
symbols' exact extern declarations are harvested verbatim from menu_data.c
(guaranteed type-consistent) and the registry takes `&sym` for scalars or `sym`
for arrays / pointer-arrays / dotted field refs (which decay to a constant
address).

Run from the repo root:  python3 scripts/gen_menu_symbols.py
"""
import json
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYMS = os.path.join(REPO, "bin", "data_json", "menus", "_symbols.json")
MENU_DATA = os.path.join(REPO, "src", "menu_data.c")
OUT_C = os.path.join(REPO, "src", "menu_symbols.c")
OUT_H = os.path.join(REPO, "src", "menu_symbols.h")

KIND_ENUM = {"functions": "SYM_FUNC", "strings": "SYM_STRING",
             "tables": "SYM_TABLE", "sprite_copies": "SYM_SPRITE_COPY",
             "buffers": "SYM_BUFFER"}


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    return text


def harvest_data_decls(src):
    """name -> exact 'extern ...;' line for every non-function extern."""
    decls = {}
    for line in src.splitlines():
        s = line.strip()
        if not s.startswith("extern ") or "(" in s:
            continue
        s = re.sub(r"\s+", " ", s)
        m = re.search(r"\b([A-Za-z_]\w*)\s*(?:\[[^\]]*\])*\s*;\s*$", s)
        if m:
            decls[m.group(1)] = s
    return decls


def main():
    syms = json.load(open(SYMS))
    src = strip_comments(open(MENU_DATA, encoding="utf-8", errors="replace").read())
    decls = harvest_data_decls(src)

    # Build the flat, de-duplicated, name-sorted symbol list.
    # kind priority if a name appears in >1 bucket (shouldn't, but be safe).
    seen = {}
    for bucket in ("functions", "tables", "sprite_copies", "buffers", "strings"):
        for name in syms.get(bucket, []):
            seen.setdefault(name, bucket)

    extern_lines = []      # de-duplicated extern declarations
    extern_emitted = set()
    rows = []              # (name, expr, kind_enum)
    missing = []

    for name in sorted(seen):
        bucket = seen[name]
        if bucket == "functions":
            if name not in extern_emitted:
                extern_lines.append("extern void %s(void);" % name)
                extern_emitted.add(name)
            rows.append((name, "(void*)%s" % name, KIND_ENUM[bucket]))
            continue
        # data symbol: resolve its (or its dotted base's) extern decl
        base = name.split(".")[0]
        decl = decls.get(base)
        if decl is None:
            missing.append(name)
            continue
        if base not in extern_emitted:
            extern_lines.append(decl)
            extern_emitted.add(base)
        # array / pointer-array / dotted -> decays to address; scalar -> &sym
        is_array = "[" in decl
        is_dotted = "." in name
        expr = ("(void*)%s" if (is_array or is_dotted) else "(void*)&%s") % name
        rows.append((name, expr, KIND_ENUM[bucket]))

    # ---- emit header ----
    with open(OUT_H, "w") as h:
        h.write("/* GENERATED by scripts/gen_menu_symbols.py — do not edit by hand.\n"
                " * Menu name->address registry; see docs/MENUS.md §2c. */\n"
                "#ifndef MENU_SYMBOLS_H\n#define MENU_SYMBOLS_H\n\n"
                "typedef enum {\n"
                "    SYM_FUNC, SYM_STRING, SYM_TABLE, SYM_SPRITE_COPY, SYM_BUFFER\n"
                "} MenuSymbolKind;\n\n"
                "typedef struct {\n"
                "    const char    *name;\n"
                "    void          *ptr;\n"
                "    unsigned char  kind;   /* MenuSymbolKind */\n"
                "} MenuSymbol;\n\n"
                "extern const MenuSymbol menuSymbols[];\n"
                "extern const int        menuSymbolsCount;\n\n"
                "/* Resolve a menu symbol name to its address (NULL if unknown). */\n"
                "void              *menu_resolve(const char *name);\n"
                "const MenuSymbol  *menu_symbol_lookup(const char *name);\n\n"
                "#endif /* MENU_SYMBOLS_H */\n")

    # ---- emit source ----
    with open(OUT_C, "w") as c:
        c.write("/* GENERATED by scripts/gen_menu_symbols.py — do not edit by hand.\n"
                " * Source: bin/data_json/menus/_symbols.json + src/menu_data.c decls.\n"
                " * See docs/MENUS.md §2c. */\n"
                '#include "menu_symbols.h"\n'
                '#include "menu_data.h"   /* types for the harvested extern decls */\n'
                "#include <string.h>\n"
                "#include <stdlib.h>\n\n"
                "/* ---- function callbacks (void(void) for address-taking) ---- */\n")
        for ln in extern_lines:
            if ln.startswith("extern void ") and ln.endswith("(void);"):
                c.write(ln + "\n")
        c.write("\n/* ---- data symbols (decls harvested verbatim from menu_data.c) ---- */\n")
        for ln in extern_lines:
            if not (ln.startswith("extern void ") and ln.endswith("(void);")):
                c.write(ln + "\n")
        c.write("\nconst MenuSymbol menuSymbols[] = {\n")
        for name, expr, kind in rows:
            c.write('    { "%s", %s, %s },\n' % (name, expr, kind))
        c.write("};\n"
                "const int menuSymbolsCount =\n"
                "    (int)(sizeof(menuSymbols) / sizeof(menuSymbols[0]));\n\n"
                "static int menu_symbol_cmp(const void *key, const void *elem)\n"
                "{\n"
                "    return strcmp((const char *)key, ((const MenuSymbol *)elem)->name);\n"
                "}\n\n"
                "const MenuSymbol *menu_symbol_lookup(const char *name)\n"
                "{\n"
                "    return (const MenuSymbol *)bsearch(name, menuSymbols,\n"
                "        (size_t)menuSymbolsCount, sizeof(menuSymbols[0]), menu_symbol_cmp);\n"
                "}\n\n"
                "void *menu_resolve(const char *name)\n"
                "{\n"
                "    const MenuSymbol *s = menu_symbol_lookup(name);\n"
                "    return s ? s->ptr : (void *)0;\n"
                "}\n")

    print("Wrote %s (%d symbols) and %s"
          % (os.path.relpath(OUT_C, REPO), len(rows), os.path.relpath(OUT_H, REPO)))
    by_kind = {}
    for _, _, k in rows:
        by_kind[k] = by_kind.get(k, 0) + 1
    for k in ("SYM_FUNC", "SYM_STRING", "SYM_TABLE", "SYM_SPRITE_COPY", "SYM_BUFFER"):
        print("  %-16s %d" % (k, by_kind.get(k, 0)))
    if missing:
        print("  WARN unresolved (%d): %r" % (len(missing), missing))


if __name__ == "__main__":
    main()
