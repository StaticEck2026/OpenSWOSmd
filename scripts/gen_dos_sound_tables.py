#!/usr/bin/env python3
"""Write src/dos_sound_tables.h from the PC game's disassembly (docs/DOS_SOUND.md).

    scripts/gen_dos_sound_tables.py <swos.asm> <PC game folder> [--copy bin/sound_dos]

The PC game keeps its commentary as one block of memory -- every file of
commentaryTable loaded end to end -- and names a line by (offset, size) into it.
This turns each pair back into the file it is, using the files' real sizes, and
fails if a pair lands anywhere but on a whole file. --copy also copies the files
the tables name (lower case) into the game's data folder.
"""
import os, re, shutil, sys

def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    copy = None
    if '--copy' in sys.argv:
        copy = sys.argv[sys.argv.index('--copy') + 1]
        args.remove(copy)
    asm_path, game = args[0], args[1]
    lines = open(asm_path, errors='replace').read().split('\n')

    strings = {}
    for l in lines:
        m = re.match(r"^(a\w+) db '([^']*)',0", l)
        if m:
            strings[m.group(1)] = m.group(2)

    def table(name):
        """The dd values of a table: label names or integers, up to the next label."""
        out, on = [], False
        for l in lines:
            if not on:
                m = re.match(r'^%s d[bd] (.*)$' % re.escape(name), l)
                if m:
                    on, l = True, 'dd ' + m.group(1)
                else:
                    continue
            m = re.match(r'^\s*d[bd] (.*)$', l)
            if m:
                body = m.group(1).split(';')[0]
                for t in body.split(','):
                    t = t.strip()
                    if not t:
                        continue
                    if t.startswith('offset '):
                        out.append(t[7:].strip())
                    else:
                        out.append(int(t[:-1], 16) if t.endswith('h') else int(t))
                continue
            if l.strip() == '' or l.lstrip().startswith(';'):
                continue
            break
        return out

    def find(rel):
        """A file of the PC game, whatever the case of its name."""
        cur = game
        for part in rel.replace('\\', '/').split('/'):
            hit = [e for e in os.listdir(cur) if e.lower() == part.lower()]
            if not hit:
                sys.exit('missing in the PC game folder: ' + rel)
            cur = os.path.join(cur, hit[0])
        return cur

    files, index = [], {}
    def fid(rel):
        key = rel.replace('\\', '/').lower()
        if key.startswith('sfx/'):
            key = key[4:]
        if key not in index:
            index[key] = len(files)
            files.append((key, find(rel)))
        return index[key]

    def names(tbl):
        return [fid(strings[x]) for x in table(tbl) if x != -1]

    out = []
    w = out.append
    w('/* Generated by scripts/gen_dos_sound_tables.py from the PC game\'s disassembly -- do not edit. */')

    effects = names('soundEffectsTable')
    intro = names('introTeamChantsTable')
    result = names('resultChantFilenames')
    endgame = names('endGameCrowdSamples')
    intro_idx = table('introTeamChantIndices')[:16]

    comm = [strings[x] for x in table('commentaryTable') if x != -1]
    offs, pos = {}, 0
    for rel in comm:
        size = os.path.getsize(find(rel))
        offs[(pos, size)] = fid(rel)
        pos += size

    pair_tables = [  # name, mask the PC game ands the random number with
        ('goalSamples', 7), ('goalkeeperSavedSamples', 7), ('ownGoalSamples', 7),
        ('nearMissesSamples', 3), ('postHitSamples', 7), ('barHitSamples', 1),
        ('keeperClaimedSamples', 7), ('goodTackleSamples', 3), ('goodPassSamples', 3),
        ('foulSamples', 7), ('dangerousPlaySamples', 3), ('itsPenaltySamples', 3),
        ('savedPenaltySamples', 3), ('missedPenaltySamples', 3), ('penaltyGoalSamples', 3),
    ]
    file_tables = [  # name, entries
        ('cornerSamplesTable', 8), ('tacticsChangeSamplesTable', 8),
        ('playerSubstitutedSamplesTable', 8), ('throwInSamplesTable', 8),
        ('redCardSamplesTable', 16), ('yellowCardSamplesTable', 16),
        ('drawSamplesTable', 8), ('completeRoutSamplesTable', 8),
        ('sensationalGameSamplesTable', 8),
    ]
    cats = []
    for name, mask in pair_tables:
        v = table(name)[:2 * (mask + 1)]
        ids = []
        for i in range(0, len(v), 2):
            key = (v[i], v[i + 1])
            if key[1] == 0:
                ids.append(255)         # a line of no length: the PC game plays nothing
                continue
            if key not in offs:
                sys.exit('%s[%d] = %r is not a whole commentary file' % (name, i // 2, key))
            ids.append(offs[key])
        if len(ids) != mask + 1:
            sys.exit('%s: %d entries, wanted %d' % (name, len(ids), mask + 1))
        cats.append((name, ids))
    for name, n in file_tables:
        ids = names(name)[:n]
        if len(ids) != n:
            sys.exit('%s: %d entries, wanted %d' % (name, len(ids), n))
        cats.append((name, ids))

    w('')
    w('static const char *const k_dosSoundFiles[] = {')
    for i, (key, _) in enumerate(files):
        w('    /* %3d */ "%s",' % (i, key))
    w('};')
    w('#define DOS_SOUND_FILES %d' % len(files))
    w('#define DOS_SOUND_NONE  255     /* a table entry of no length */')
    def arr(cname, ids, comment=''):
        w('static const uint8_t %s[%d] = { %s };%s' % (cname, len(ids), ', '.join(map(str, ids)), comment))
    w('')
    arr('k_dosEffects', effects, '   /* soundEffectsTable */')
    arr('k_dosIntroChants', intro, '   /* introTeamChantsTable */')
    w('static const int8_t k_dosIntroChantByColour[16] = { %s };' % ', '.join(map(str, intro_idx)))
    arr('k_dosResultChants', result, '   /* resultChantFilenames */')
    arr('k_dosEndGameCrowd', endgame, '   /* endGameCrowdSamples */')
    w('')
    for name, ids in cats:
        arr('k_dos_' + name, ids)
    if len(files) > 254:
        sys.exit('more than 255 files: widen the tables')

    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'dos_sound_tables.h')
    open(dst, 'w', newline='\n').write('\n'.join(out) + '\n')
    total = sum(os.path.getsize(p) for _, p in files)
    print('%d files, %.1f MB -> %s' % (len(files), total / 1e6, os.path.normpath(dst)))
    if copy:
        for key, path in files:
            d = os.path.join(copy, key)
            os.makedirs(os.path.dirname(d), exist_ok=True)
            shutil.copyfile(path, d)
        # The menu music and its instruments (src/dos_music.c): not in any table.
        for rel in ('menu.xmi', 'sample.ad'):
            shutil.copyfile(find(rel), os.path.join(copy, rel))
        print('copied to ' + copy)

if __name__ == '__main__':
    main()
