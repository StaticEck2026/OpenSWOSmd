#!/usr/bin/env bash
# Writes include/swos_build.h -- the commit this binary was built from.
#
# Every tester bug report used to start with "which build is this?", and there
# was no way to answer it: nothing in the binary said. One macOS report cost a
# whole session because the build predated the fix it was testing
# (docs/TESTS.md, release provenance). So the stamp is generated here and shown
# on the main menu, in the window title, in SWOS.log and by --version.
#
# Called at PARSE TIME by both makefiles, so it runs on every build. Two things
# keep that cheap and non-disruptive:
#   - the file is rewritten ONLY when its contents change, so an unchanged
#     commit does not force a recompile of the one object that includes it;
#   - the dirty check looks at the SOURCE paths only, not the whole tree (bin/
#     alone is tens of thousands of files on /mnt/c, and a screenshot dropped in
#     bin/ should not mark the build dirty).
#
# Not committed: include/swos_build.h is gitignored. A tarball with no git
# history still builds -- the id becomes "unknown".
set -u
cd "$(dirname "$0")/.."

OUT=include/swos_build.h

if git rev-parse --git-dir >/dev/null 2>&1; then
    ID=$(git rev-parse --short HEAD 2>/dev/null || echo unknown)
    DATE=$(git log -1 --format=%cd --date=short 2>/dev/null || date +%Y-%m-%d)
    # -dirty means "this is NOT that commit": the single most useful thing to
    # know when a drop behaves unlike the source you are reading.
    if ! git diff --quiet HEAD -- src include Makefile Makefile.amiga scripts 2>/dev/null; then
        ID="$ID-dirty"
    fi
else
    ID=unknown
    DATE=$(date +%Y-%m-%d)
fi

# The in-game font has no lowercase glyphs (kSmallFontWidths is 0 for a-z), so
# the on-screen form is uppercased here rather than at runtime.
ID_UC=$(printf '%s' "$ID" | tr '[:lower:]' '[:upper:]')

NEW="/* GENERATED by scripts/gen_build_info.sh -- do not edit, do not commit.
 * Regenerated at parse time by both makefiles; written only when it changes. */
#ifndef SWOS_BUILD_H
#define SWOS_BUILD_H

#define SWOS_BUILD_ID      \"$ID\"
#define SWOS_BUILD_ID_UC   \"$ID_UC\"
#define SWOS_BUILD_DATE    \"$DATE\"

#endif /* SWOS_BUILD_H */"

if [ ! -f "$OUT" ] || [ "$(cat "$OUT" 2>/dev/null)" != "$NEW" ]; then
    printf '%s\n' "$NEW" > "$OUT"
fi
