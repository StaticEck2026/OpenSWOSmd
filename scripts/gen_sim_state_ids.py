#!/usr/bin/env python3
"""Generate src/sim_state_ids.h: the stable numbering of the static tables that match
state points into (docs/ROLLBACK.md, "Pointers").

A pointer in the match state cannot cross from one build to another: the same animation
table sits at a different address in a 32-bit, a 64-bit or a Windows executable. The
portable encoding (src/sim_state.c) writes it as an IDENTITY instead -- the table's
position in a list that every build compiles identically. This script makes that list,
sorted by name, from the definitions in the source:

  SIM_ANIM_TABLES(X)    X(type, name)          every AnimTable* in src/sprite_data.c
  SIM_FRAME_ARRAYS(X)   X(type, name, count)   every int16_t frame-index array there,
                                               plus EXTRA_FRAME_ARRAYS defined elsewhere

    scripts/gen_sim_state_ids.py            # rewrite src/sim_state_ids.h
    scripts/gen_sim_state_ids.py --check    # exit 1 if it is out of date

Run it whenever an animation table or frame array is added, renamed or removed. The
rollback rig refuses a match state holding a pointer it cannot identify, so a stale
list shows up as a failure rather than as a silent desync.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "sim_state_ids.h"

# Frame-index arrays a Sprite can point at that are not defined in sprite_data.c.
# (file, name) -- the definition is read from the file, so its type and size are checked.
EXTRA_FRAME_ARRAYS = [
    ("src/swos_amiga_data_imports.c", "_ballMovingFrameIndices"),   # ball_physics.c
    ("src/swos_amiga_data_imports.c", "_ballStaticFrameIndices"),
]

DEF_ANIM = re.compile(r"^\s*(AnimTable(?:_\d+)?)\s+(_\w+)\s*=", re.M)
DEF_ARRAY = re.compile(r"^\s*(u?int16_t)\s+(_\w+)\s*\[\s*(\d+)\s*\]", re.M)


def generate():
    sprite_data = (ROOT / "src" / "sprite_data.c").read_text()
    anims = sorted(DEF_ANIM.findall(sprite_data), key=lambda t: t[1])
    arrays = {name: (typ, count) for typ, name, count in DEF_ARRAY.findall(sprite_data)}
    for path, name in EXTRA_FRAME_ARRAYS:
        found = [(t, c) for t, n, c in DEF_ARRAY.findall((ROOT / path).read_text()) if n == name]
        if len(found) != 1:
            sys.exit("gen_sim_state_ids: %s is not defined exactly once in %s" % (name, path))
        arrays[name] = found[0]
    lines = [
        "/* Generated by scripts/gen_sim_state_ids.py -- do not edit. */",
        "/* The stable numbering of the static tables match state points into: a pointer",
        " * travels as its target's position in these lists (src/sim_state.c). */",
        "#ifndef SIM_STATE_IDS_H",
        "#define SIM_STATE_IDS_H",
        "",
        "#define SIM_ANIM_TABLE_COUNT %d" % len(anims),
        "#define SIM_ANIM_TABLES(X) \\",
    ]
    lines += ["    X(%s, %s) \\" % (t, n) for t, n in anims]
    lines += ["", "#define SIM_FRAME_ARRAY_COUNT %d" % len(arrays), "#define SIM_FRAME_ARRAYS(X) \\"]
    lines += ["    X(%s, %s, %s) \\" % (arrays[n][0], n, arrays[n][1]) for n in sorted(arrays)]
    lines += ["", "#endif /* SIM_STATE_IDS_H */", ""]
    return "\n".join(lines)


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print("src/sim_state_ids.h is out of date: run scripts/gen_sim_state_ids.py")
            sys.exit(1)
        return
    OUT.write_text(text)
    print("wrote %s" % OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
