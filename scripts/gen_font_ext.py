#!/usr/bin/env python3
"""Generate src/font_ext_script.inc + src/font_ext_conv.inc from the font tool's
integration.txt (C:\\Projects\\Python\\SWOS_Font\\integration.txt, produced by
swos_font.py alongside new_charset.png).

font_ext_script.inc : glyph-extract triples appended to introMenuImageScript so
                      the extra glyphs (accented capitals, full ASCII punctuation,
                      $) are carved out of the extended charset.raw (slots 256+).
font_ext_conv.inc   : SB(idx, smallSlot, bigSlot) statements applied by
                      FontExt_ApplyConv() — maps each character byte to its glyph,
                      plus lowercase a-z -> uppercase glyph and the Ä/Ö/Ü Latin-1
                      remap. conversionTable is uint16 so slots can exceed 255.

Usage:  python3 scripts/gen_font_ext.py [path/to/integration.txt]
"""
import os, re, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT = "/mnt/c/Projects/Python/SWOS_Font/integration.txt"

def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    script, conv = [], []
    for ln in open(src, encoding="utf-8").read().splitlines():
        code = ln.split('#')[0].strip()
        if not code:
            continue
        m = re.match(r'^(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+),?$', code)
        if m and m.group(1).upper().startswith('0XC'):
            script.append(f"    {m.group(1)}, {m.group(2)}, {m.group(3)},"); continue
        m = re.match(r'small\.conv\[(0x[0-9A-Fa-f]+)\]=(\d+)\s+big\.conv\[0x[0-9A-Fa-f]+\]=(\d+)', code)
        if m:
            conv.append(f"    SB({m.group(1)}, {m.group(2)}, {m.group(3)});"); continue
        m = re.match(r'conv\[(0x[0-9A-Fa-f]+)\]=(\d+)', code)
        if m:
            conv.append(f"    SB({m.group(1)}, {m.group(2)}, {m.group(2)});")
    open(os.path.join(REPO, "src", "font_ext_script.inc"), "w").write(
        "/* Generated by scripts/gen_font_ext.py from SWOS_Font/integration.txt.\n"
        " * Glyph extracts (slots 256+) appended into introMenuImageScript. */\n"
        + "\n".join(script) + "\n")
    open(os.path.join(REPO, "src", "font_ext_conv.inc"), "w").write(
        "/* Generated by scripts/gen_font_ext.py from SWOS_Font/integration.txt.\n"
        " * conversionTable mappings + lowercase a-z. #included by FontExt_ApplyConv(). */\n"
        + "\n".join(conv) + "\n")
    print(f"wrote font_ext_script.inc ({len(script)} entries) + font_ext_conv.inc ({len(conv)} stmts)")

if __name__ == "__main__":
    main()
