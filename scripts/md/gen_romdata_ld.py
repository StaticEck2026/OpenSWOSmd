#!/usr/bin/env python3
"""Turn scripts/md/rom_tables.txt into the linker-script fragment md.ld INCLUDEs.

Each name in the list is a shared-engine global that is declared without `const` but
is never written while the Mega Drive build runs (an animation table, a formation...).
Its section, .data.<name> (the build uses -fdata-sections), is placed in ROM with
.rodata instead of being copied to work RAM; a zero-initialised one, .bss.<name>, becomes
zeros in ROM. See docs/MEGADRIVE.md "RAM".

    gen_romdata_ld.py rom_tables.txt out.ld
"""
import sys

names = []
for line in open(sys.argv[1]):
    line = line.split("#", 1)[0].strip()
    if line:
        names.append(line)
with open(sys.argv[2], "w") as f:
    f.write("/* Generated by scripts/md/gen_romdata_ld.py from scripts/md/rom_tables.txt */\n")
    for n in names:
        f.write("*(.data.%s)\n" % n)
        f.write("*(.bss.%s)\n" % n)
