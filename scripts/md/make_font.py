#!/usr/bin/env python3
"""Render the Mega Drive build's fallback 8x8 font (ASCII 32..127) from a free TTF.

The game's own fonts come from the player's SWOS data (scripts/md/make_md_data.py takes
them from the charset when it is there). This one is what the ROM shows without it, and
what the panic screen always uses. Output: a C array of 96 4bpp tiles, ink = colour 2,
shadow = colour 3 one pixel down-right, as SWOS draws its text (white and black in the
game palette, so text needs no palette of its own).

    make_font.py out.c [font.ttf]
"""
import sys
from PIL import Image, ImageDraw, ImageFont

CANDIDATES = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    "/Library/Fonts/Arial Bold.ttf",
    "C:/Windows/Fonts/consolab.ttf",
]


def load_font(path):
    for p in ([path] if path else []) + CANDIDATES:
        try:
            return ImageFont.truetype(p, 9)
        except OSError:
            continue
    return ImageFont.load_default()


def glyph(font, ch):
    img = Image.new("L", (16, 16), 0)
    d = ImageDraw.Draw(img)
    d.text((0, -2), ch, fill=255, font=font)
    ink = [[1 if img.getpixel((x, y)) >= 110 else 0 for x in range(7)] for y in range(7)]
    # centre horizontally in 7 columns
    cols = [x for x in range(7) if any(ink[y][x] for y in range(7))]
    if cols:
        shift = (7 - (cols[-1] - cols[0] + 1)) // 2 - cols[0]
        ink = [[ink[y][x - shift] if 0 <= x - shift < 7 else 0 for x in range(7)] for y in range(7)]
    cell = [[0] * 8 for _ in range(8)]
    for y in range(7):
        for x in range(7):
            if ink[y][x]:
                cell[y][x] = 2
    for y in range(7):
        for x in range(7):
            if ink[y][x] and cell[y + 1][x + 1] == 0:
                cell[y + 1][x + 1] = 3
    return cell


def tile_words(cell):
    out = []
    for row in cell:
        v = 0
        for px in row:
            v = (v << 4) | px
        out.append(v)
    return out


def main():
    out = sys.argv[1]
    font = load_font(sys.argv[2] if len(sys.argv) > 2 else None)
    lines = ["/* Generated by scripts/md/make_font.py -- do not edit. */",
             "#include <stdint.h>",
             "const uint32_t md_font_tiles[96 * 8] __attribute__((aligned(2))) = {"]
    for c in range(32, 128):
        cell = glyph(font, chr(c)) if c < 127 else [[0] * 8 for _ in range(8)]
        lines.append("    " + ", ".join("0x%08X" % w for w in tile_words(cell)) + ",  /* %r */" % chr(c))
    lines.append("};")
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
